"""Synthesize the spoken praise clips and the lookup table the mini program uses to find them.

Usage: python scripts/make_speech.py
Needs Windows (its built-in zh-CN voice, via PowerShell System.Speech) and ffmpeg on PATH.

Clips go to scripts/output/speech/ (never packaged); upload that folder to cloud storage as `speech/`.
utils/practice/speech-clips.js is rewritten with text -> file name. File names come from the text itself,
so re-running only adds clips for new phrases; unchanged phrases keep their names and need no re-upload.

PHRASES must match the cheer titles/subtitles in the pages. A phrase missing here is simply not read aloud.
"""
import hashlib
import json
import re
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT_DIR = ROOT / "scripts" / "output" / "speech"
CLIPS_MODULE = ROOT / "utils" / "practice" / "speech-clips.js"
VOICE = "Microsoft Huihui Desktop"
SPEECH_RATE = 1  # SAPI scale -10..10; slightly brisk sounds more cheerful
MAX_COMBO = 30
MAX_STREAK_SUBTITLE = 30

# Same rule as toSpeakableText in utils/practice/speech.js: the lookup key is the text with emoji dropped.
UNSPEAKABLE = re.compile("[\U0001F000-\U0001FAFF←-⯿️‍]")


def speakable(text):
    return re.sub(r"\s+", " ", UNSPEAKABLE.sub("", text)).strip()


def build_phrases():
    phrases = [
        # 加减运算 · 练习 (pages/practice/arithmetic/play.js)
        "太棒啦！", "你是天才吧！", "聪明到发光！", "哇！全对！", "超级厉害！", "算得好快呀！", "小小数学家！", "你真了不起！",
        "改对啦！真棒！", "坚持就是胜利！", "新纪录！",
        "真棒！连对 5 题", "势不可挡！", "数学小天才！", "无人能敌！", "传奇诞生！",
        "奖励你一颗星星 ⭐", "🎁 得到一个宝箱！去「我的宝箱」打开",
        # 加减运算 · 限时考试 (pages/practice/arithmetic/exam.js)
        "100 分！", "满分小状元", "80 分！", "85 分！", "90 分！", "95 分！", "超级棒", "真不错",
        # 九九神功 · 修炼 (pages/practice/multiplication/train.js)
        "好招式！", "内力大增！", "一招制胜！", "身手不凡！", "出手如电！", "功力见长！", "突破成功！", "功力更加深厚",
        # 九九神功 · 论剑 (pages/practice/multiplication/exam.js)
        "好！", "漂亮！", "稳！", "准！", "快！", "神功大成！", "九九八十一，尽在掌握",
        # 解谜闯关 (pages/game/play/play.js)
        "过关啦！", "太厉害了！", "答对啦！", "一猜就中！", "零失误，满分过关！",
        "全部闯过啦！", "你是真正的喵喵状元郎", "称号升级啦！", "解锁宝箱！", "快去打开看看里面有什么",
    ]
    techniques = ["入门心法", "两仪掌", "三才剑", "四象拳", "五行步", "六合刀", "七星指", "八卦掌", "九九归一"]
    phrases += [f"{name} 练成！" for name in techniques]
    phrases += [f"{combo} 连击！" for combo in range(3, MAX_COMBO + 1)]
    phrases += [f"已经连对 {streak} 题啦！" for streak in range(2, MAX_STREAK_SUBTITLE + 1)]
    return sorted({speakable(phrase) for phrase in phrases})


def clip_name(text):
    return hashlib.md5(text.encode("utf-8")).hexdigest()[:12] + ".mp3"


def synthesize_wavs(jobs, work_dir):
    """One PowerShell run for all phrases; starting the speech engine per phrase is slow."""
    job_file = work_dir / "jobs.json"
    job_file.write_text(json.dumps(jobs, ensure_ascii=False), encoding="utf-8")
    script = f"""
Add-Type -AssemblyName System.Speech
$synth = New-Object System.Speech.Synthesis.SpeechSynthesizer
$synth.SelectVoice('{VOICE}')
$synth.Rate = {SPEECH_RATE}
foreach ($job in (Get-Content -Raw -Encoding UTF8 '{job_file}' | ConvertFrom-Json)) {{
  $synth.SetOutputToWaveFile($job.wav)
  $synth.Speak($job.text)
}}
$synth.Dispose()
"""
    subprocess.run(["powershell", "-NoProfile", "-Command", script], check=True)


def to_mp3(wav, mp3):
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-i", str(wav), "-ac", "1", "-ar", "24000", "-b:a", "32k", str(mp3)],
        check=True,
    )


def write_clips_module(clips):
    lines = [
        "// Generated by scripts/make_speech.py - do not edit by hand; add phrases there and re-run it.",
        "// Spoken text (emoji removed) -> clip file name in cloud storage under speech/.",
        "module.exports = {",
    ]
    lines += [f"  {json.dumps(text, ensure_ascii=False)}: '{name}'," for text, name in clips.items()]
    lines[-1] = lines[-1].rstrip(",")
    lines.append("}")
    CLIPS_MODULE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    clips = {text: clip_name(text) for text in build_phrases()}
    missing = {text: name for text, name in clips.items() if not (OUTPUT_DIR / name).exists()}
    with tempfile.TemporaryDirectory() as temp:
        work_dir = Path(temp)
        jobs = [{"text": text, "wav": str(work_dir / name.replace(".mp3", ".wav"))} for text, name in missing.items()]
        if jobs:
            synthesize_wavs(jobs, work_dir)
        for job, name in zip(jobs, missing.values()):
            to_mp3(job["wav"], OUTPUT_DIR / name)
    write_clips_module(clips)
    print(f"{len(clips)} phrases, {len(missing)} new clips -> {OUTPUT_DIR}")


if __name__ == "__main__":
    main()
